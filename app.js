/* ---------- 专注计时器（25/45/60分钟） ---------- */
const TIMER_MODES = [25, 45, 60];
let timerLeft = TIMER_MODES[state.timerMode] * 60;
let timerRunning = false;
let timerInt = null;
let focusAccum = 0;
let focusSaveTick = 0;

function fmtTime(sec) {
  const m = Math.floor(sec / 60), s = sec % 60;
  return pad2(m) + ":" + pad2(s);
}

function renderTimer() {
  if ($("timer-display")) $("timer-display").textContent = fmtTime(timerLeft);
  const mins = Math.round(((state.focus[todayKey()] || 0)) / 60);
  if ($("timer-status-text")) {
    $("timer-status-text").textContent = timerRunning
      ? "🍅 专注中 (今日" + mins + "m)"
      : "🍅 专注 " + TIMER_MODES[state.timerMode] + "m (今日" + mins + "m)";
  }
}

function stopInterval() {
  if (timerInt) { clearInterval(timerInt); timerInt = null; }
}

function addFocus(seconds) {
  const key = todayKey();
  state.focus[key] = (state.focus[key] || 0) + seconds;
}

$("timer-toggle-btn").addEventListener("click", () => {
  if (timerRunning) {
    timerRunning = false;
    stopInterval();
    addFocus(focusAccum); focusAccum = 0;
    save();
    $("timer-toggle-btn").textContent = "▶ 继续";
  } else {
    timerRunning = true;
    focusAccum = 0;
    timerInt = setInterval(() => {
      timerLeft -= 1;
      focusAccum += 1;
      focusSaveTick += 1;
      if (focusSaveTick >= 15) {
        addFocus(focusAccum); focusAccum = 0; focusSaveTick = 0; save();
      }
      if (timerLeft <= 0) {
        timerLeft = 0;
        timerRunning = false;
        stopInterval();
        addFocus(focusAccum); focusAccum = 0; focusSaveTick = 0;
        save();
        $("timer-toggle-btn").textContent = "▶ 开始";
        toast("⏰ 本轮专注完成！起身活动 5 分钟吧");
      }
      renderTimer();
    }, 1000);
    $("timer-toggle-btn").textContent = "⏸ 暂停";
  }
  renderTimer();
});

$("timer-reset-btn").addEventListener("click", () => {
  timerRunning = false;
  stopInterval();
  if (focusAccum > 0) { addFocus(focusAccum); focusAccum = 0; save(); }
  timerLeft = TIMER_MODES[state.timerMode] * 60;
  $("timer-toggle-btn").textContent = "▶ 开始";
  renderTimer();
});

$("timer-mode-btn").addEventListener("click", () => {
  state.timerMode = (state.timerMode + 1) % TIMER_MODES.length;
  save();
  timerRunning = false;
  stopInterval();
  timerLeft = TIMER_MODES[state.timerMode] * 60;
  $("timer-toggle-btn").textContent = "▶ 开始";
  renderTimer();
  toast("已切换为 " + TIMER_MODES[state.timerMode] + " 分钟专注模式");
});

